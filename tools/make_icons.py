"""Icons of HAFS from the logo (design/logo/logo-c.svg, draft C "two halves").

    python tools/make_icons.py

Writes:
- mydiet/icon.png (128 px, the HA app's icon), mydiet/logo.png (logo with the word mark "HAFS", for the app store page)
- mydiet/app/static/icon.svg (favicon of the web interface)
- app/android/.../mipmap-*/ic_launcher.png (legacy launcher icon) and an adaptive icon: foreground PNGs
  (mipmap-*/ic_launcher_foreground.png) on a vector background with the two halves (drawable/ic_launcher_background.xml)
- app/windows/runner/resources/app_icon.ico

Needs Playwright with Chromium (as docs/make_screenshots.py) and Pillow.
"""
from __future__ import annotations

import io
import re
import shutil
from pathlib import Path

from PIL import Image
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent.parent
LOGO = ROOT / "design" / "logo" / "logo-c.svg"
RES = ROOT / "app" / "android" / "app" / "src" / "main" / "res"
DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}


def svg_text() -> str:
    return LOGO.read_text(encoding="utf-8")


def sized(svg: str, px: int) -> str:
    return re.sub(r'width="\d+" height="\d+"', f'width="{px}" height="{px}"', svg, count=1)


def foreground(svg: str) -> str:
    """The drawing without the two coloured halves, smaller, for the adaptive icon's safe zone."""
    body = re.sub(r"<defs>.*?</defs>", "", svg, flags=re.S)
    body = re.sub(r'<g clip-path="url\(#r\)">.*?</g>', "", body, count=1, flags=re.S)
    inner = body[body.index(">", body.index("<svg")) + 1: body.rindex("</svg>")]
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">'
            f'<g transform="translate(256 256) scale(0.8) translate(-256 -256)">{inner}</g></svg>')


def render(page, svg: str, width: int, height: int | None = None, extra: str = "") -> bytes:
    height = height or width
    page.set_viewport_size({"width": width, "height": height})
    page.set_content(f'<html><body style="margin:0;background:transparent;width:{width}px;height:{height}px;'
                     f'display:flex;align-items:center;gap:{width // 20}px">{svg}{extra}</body></html>')
    return page.screenshot(omit_background=True, clip={"x": 0, "y": 0, "width": width, "height": height})


def main() -> None:
    svg = svg_text()
    (ROOT / "mydiet" / "app" / "static" / "icon.svg").write_text(svg, encoding="utf-8", newline="\n")
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page(device_scale_factor=1)
        (ROOT / "mydiet" / "icon.png").write_bytes(render(page, sized(svg, 128), 128))
        word = ('<span style="font:700 64px/1 \'Segoe UI\',Roboto,Arial,sans-serif;letter-spacing:2px;'
                'color:#37474F">HAFS</span>')
        (ROOT / "mydiet" / "logo.png").write_bytes(render(page, sized(svg, 100), 250, 100, word))
        for name, k in DENSITIES.items():
            folder = RES / f"mipmap-{name}"
            folder.mkdir(parents=True, exist_ok=True)
            (folder / "ic_launcher.png").write_bytes(render(page, sized(svg, int(48 * k)), int(48 * k)))
            (folder / "ic_launcher_foreground.png").write_bytes(render(page, sized(foreground(svg), int(108 * k)), int(108 * k)))
        big = Image.open(io.BytesIO(render(page, sized(svg, 256), 256)))
        browser.close()
    ico = ROOT / "app" / "windows" / "runner" / "resources" / "app_icon.ico"
    big.save(ico, sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    any_dpi = RES / "mipmap-anydpi-v26"
    any_dpi.mkdir(exist_ok=True)
    (any_dpi / "ic_launcher.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tools/make_icons.py: the two halves of the logo behind the drawing. -->\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@drawable/ic_launcher_background"/>\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>\n'
        '    <monochrome android:drawable="@mipmap/ic_launcher_foreground"/>\n'
        '</adaptive-icon>\n', encoding="utf-8", newline="\n")
    (RES / "drawable" / "ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tools/make_icons.py: nutrition (left) and training (right), colours from design/tokens.json. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp"\n'
        '    android:viewportWidth="108" android:viewportHeight="108">\n'
        '    <path android:fillColor="#2E7D5B" android:pathData="M0,0h54v108h-54z"/>\n'
        '    <path android:fillColor="#37474F" android:pathData="M54,0h54v108h-54z"/>\n'
        '</vector>\n', encoding="utf-8", newline="\n")
    shutil.copyfile(ROOT / "mydiet" / "icon.png", ROOT / "design" / "logo" / "icon-128.png")
    print("icons written")


if __name__ == "__main__":
    main()
